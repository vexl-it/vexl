import {SqlClient} from '@effect/sql'
import {Effect} from 'effect'

export default Effect.flatMap(
  SqlClient.SqlClient,
  (sql) => sql`
    CREATE TABLE banned_number (
      id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_banned_number PRIMARY KEY,
      phone_number varchar NOT NULL CONSTRAINT banned_number_phone_number_uq UNIQUE,
      hash varchar NOT NULL CONSTRAINT banned_number_hash_uq UNIQUE,
      note text,
      created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
    );
  `
)
